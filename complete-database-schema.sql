-- Posts table with all columns
CREATE TABLE IF NOT EXISTS public.posts (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  student_name TEXT NOT NULL CHECK (char_length(student_name) >= 2),
  title TEXT NOT NULL CHECK (char_length(title) >= 3),
  content TEXT NOT NULL CHECK (char_length(content) >= 1),
  category TEXT NOT NULL CHECK (category = ANY (ARRAY['video'::text, 'design'::text, 'poem'::text, 'story'::text, 'free'::text, 'powerpoint'::text])),
  image_url TEXT,
  video_url TEXT,
  document_url TEXT,
  emirate TEXT DEFAULT 'دبي' CHECK (emirate = ANY (ARRAY['أبوظبي'::text, 'دبي'::text, 'الشارقة'::text, 'عجمان'::text, 'أم القيوين'::text, 'رأس الخيمة'::text, 'الفجيرة'::text])),
  likes INTEGER NOT NULL DEFAULT 0,
  teacher_rating INTEGER DEFAULT 0,
  is_teacher_choice BOOLEAN DEFAULT false,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Comments table
CREATE TABLE IF NOT EXISTS public.comments (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  post_id UUID NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  student_name TEXT NOT NULL CHECK (char_length(student_name) >= 2),
  content TEXT NOT NULL CHECK (char_length(content) >= 3),
  is_teacher BOOLEAN DEFAULT false,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- App settings table
CREATE TABLE IF NOT EXISTS public.app_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key TEXT NOT NULL UNIQUE,
  setting_value BOOLEAN NOT NULL DEFAULT false,
  description TEXT,
  last_updated_by TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Post likes tables
CREATE TABLE IF NOT EXISTS public.post_likes_audit (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  post_id UUID NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  user_hash TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(post_id, user_hash)
);

CREATE TABLE IF NOT EXISTS public.post_likes (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  post_id UUID NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  user_hash TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Notifications table
CREATE TABLE IF NOT EXISTS public.notifications (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  post_id UUID REFERENCES public.posts(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  message TEXT NOT NULL,
  student_name TEXT,
  actor_name TEXT,
  is_read BOOLEAN DEFAULT false,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now())
);

-- User avatars table
CREATE TABLE IF NOT EXISTS public.user_avatars (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  student_name TEXT NOT NULL UNIQUE,
  avatar_parts JSONB DEFAULT '{}'::jsonb,
  total_likes INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Creative rooms table
CREATE TABLE IF NOT EXISTS public.creative_rooms (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  student_name TEXT NOT NULL UNIQUE,
  room_theme TEXT DEFAULT 'default',
  featured_works JSONB DEFAULT '[]'::jsonb,
  visitor_count INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Creative signatures table
CREATE TABLE IF NOT EXISTS public.creative_signatures (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  student_name TEXT NOT NULL UNIQUE,
  signature_type TEXT,
  signature_data JSONB,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Personal museums table
CREATE TABLE IF NOT EXISTS public.personal_museums (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  student_name TEXT NOT NULL UNIQUE,
  featured_works JSONB DEFAULT '[]'::jsonb,
  museum_theme TEXT DEFAULT 'classic',
  visitor_count INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Advertise requests table
CREATE TABLE IF NOT EXISTS public.advertise_requests (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  requester_name TEXT NOT NULL,
  organization TEXT NOT NULL,
  email TEXT NOT NULL,
  package_type TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Site stats view
CREATE OR REPLACE VIEW public.site_stats AS
SELECT
  count(*) as total_posts,
  count(distinct student_name) as total_students,
  sum(likes) as total_likes
FROM public.posts;

