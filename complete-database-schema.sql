-- Like functions
CREATE OR REPLACE FUNCTION public.like_post(p_post_id UUID, p_user_hash TEXT)
RETURNS TEXT AS $$
BEGIN
  INSERT INTO public.post_likes_audit (post_id, user_hash)
  VALUES (p_post_id, p_user_hash);

  UPDATE public.posts
  SET likes = likes + 1
  WHERE id = p_post_id;

  RETURN 'LIKE_ADDED';
EXCEPTION WHEN unique_violation THEN
  RETURN 'ALREADY_LIKED';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.add_multiple_like(p_post_id UUID, p_user_hash TEXT)
RETURNS TEXT AS $$
BEGIN
  INSERT INTO public.post_likes (post_id, user_hash)
  VALUES (p_post_id, p_user_hash);

  UPDATE public.posts
  SET likes = likes + 1
  WHERE id = p_post_id;

  RETURN 'LIKE_ADDED';
EXCEPTION WHEN OTHERS THEN
  RETURN 'ERROR';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Notification function
CREATE OR REPLACE FUNCTION notify_on_comment()
RETURNS TRIGGER AS $$
DECLARE
    v_student_name TEXT;
BEGIN
    SELECT student_name INTO v_student_name FROM public.posts WHERE id = NEW.post_id;

    INSERT INTO public.notifications (post_id, type, message, student_name, actor_name)
    VALUES (
        NEW.post_id,
        'comment',
        'قام ' || NEW.student_name || ' بالتعليق على مشاركتك!',
        v_student_name,
        NEW.student_name
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

